import json,io,base64,glob
from PIL import Image
K={"States of matter and the particle model":"pnm1","Bonding and structure":"bond","Stoichiometry":"stoi","Electrochemistry":"elec","Energetics":"ener","Rate (speed) of reaction":"rate","Redox":"redox","Reversible reactions":"rev","Periodic Table and group properties":"ptab","Preparation of salts":"salts","Properties of acids and bases":"acids","Types of oxides":"oxides","Air and rust":"air","Carbon dioxide and methane":"co2","Extraction of metals":"extr","Nitrogen and fertilisers":"nitro","Reactivity series":"react","Uses of metals":"uses","Water":"water"}
D={}
for t,k in K.items():
    d=json.load(open(f'out/{k}/{k}.json'))
    for q,fs in d['figs'].items():
        L=[]
        for f in fs:
            im=Image.open(f'out/{k}/'+f['f']).convert('L');b=io.BytesIO();im.quantize(16).save(b,'PNG',optimize=True)
            L.append([im.width,'data:image/png;base64,'+base64.b64encode(b.getvalue()).decode()])
        D[t+'|'+q]=L
js='''/* data9_tq.js - the diagrams of the IGCSE 0620 topical questions, cut from the teacher's question sheets (scans, watermark removed).
   Replaces the redrawn diagrams, tables and written descriptions in those questions. Generated by tq/gen.py. */
(function(T){
  const RX=/topical question, (.+), Question (\\d+)/;
  const isFig=el=>/^(FIGURE|TABLE|SVG|svg|IMG)$/.test(el.tagName)||(el.tagName==="DIV"&&!!el.querySelector("table,svg,figure,img")&&!el.querySelector("p,ol,ul"))
    ||(el.tagName==="P"&&el.children.length===1&&/^(I|EM)$/.test(el.children[0].tagName)&&el.textContent.trim()===el.children[0].textContent.trim()&&/^\\s*\\(?\\s*(the |a |an )?(diagram|apparatus|graph|table|figure|grid|drawing|structure|outline)/i.test(el.textContent)&&!/^\\s*(sketch|draw|use)/i.test(el.textContent));
  const html=L=>L.map(x=>`<figure class="tqf"><img src="${x[1]}" alt="Diagram from the question paper" data-in="${(x[0]/150).toFixed(2)}" style="width:${Math.round(x[0]*0.72)}px"></figure>`).join("");
  let n=0;
  U.forEach(u=>(u.pp||[]).forEach(q=>{const m=String(q.src||"").match(RX);if(!m)return;const L=T[m[1]+"|"+m[2]];if(!L)return;
    const d=document.createElement("div");d.innerHTML=q.q;let at=-1;
    [...d.children].forEach((el,i)=>{if(isFig(el)){if(at<0)at=i;el.setAttribute("data-rm","1")}});
    const kids=[...d.children],P1=kids.find(e=>e.tagName==="P");
    const mk=a=>{const x=document.createElement("div");x.innerHTML=html(a);const f=document.createDocumentFragment();[...x.childNodes].forEach(c=>f.appendChild(c));return f};
    let rest=L;
    if(L.length>1&&P1&&kids.indexOf(P1)<(at<0?1e9:at)){P1.after(mk([L[0]]));rest=L.slice(1)}
    if(at>=0)d.insertBefore(mk(rest),kids[at]);else{const ps=[...d.children].filter(e=>e.tagName==="P");const ref=rest===L?P1:ps[ps.length-1];if(ref)ref.after(mk(rest));else d.prepend(mk(rest))}
    d.querySelectorAll("[data-rm]").forEach(e=>e.remove());q.q=d.innerHTML;n++}));
})('''+json.dumps(D,separators=(',',':'))+');\n'
open('/home/claude/hub/data9_tq.js','w').write(js);print(len(D),len(js)/1e6,'MB')
